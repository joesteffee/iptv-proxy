//! Rewrites a playlist entry's URL so it points back at this proxy.
//!
//! Port of `replaceURL` from `pkg/server/server.go`. The output shape is load-bearing: clients
//! store these URLs, so changing them breaks every playlist already handed out.

use crate::config::ProxyConfig;
use crate::url::Url;
use std::fmt;

/// Something prevented a track URL from being rewritten.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RewriteError(pub String);

impl fmt::Display for RewriteError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}

impl std::error::Error for RewriteError {}

/// Rewrites `uri` for the playlist entry at `track_index`.
///
/// * `xtream == true` — the URI was generated by this proxy's own Xtream layer, so the provider
///   credentials are swapped for the proxy's. Live entries (`/{user}/{pass}/{id}`) additionally gain
///   the `/live/` prefix the Xtream live route expects; movie and series entries keep their prefix.
/// * `xtream == false` — a plain M3U entry becomes `/{anti_collision}/{user}/{pass}/{index}/{base}`.
///
/// The original query string is dropped, as in Go: the proxy routes do not read it.
pub fn rewrite_uri(
    config: &ProxyConfig,
    anti_collision: &str,
    uri: &str,
    track_index: usize,
    xtream: bool,
) -> Result<String, RewriteError> {
    let parsed = Url::parse(uri).map_err(RewriteError)?;

    let custom_endpoint = config.custom_endpoint.trim_matches('/');
    let custom_end = if custom_endpoint.is_empty() {
        String::new()
    } else {
        format!("/{custom_endpoint}")
    };

    let proxy_user = config.user.path_escape();
    let proxy_pass = config.password.path_escape();

    let mut uri_path = parsed.path.clone();
    if xtream {
        let xtream_user = config.xtream_user.path_escape();
        let xtream_pass = config.xtream_password.path_escape();
        let live_prefix = format!("/{xtream_user}/{xtream_pass}/");

        if let Some(stream_id) = uri_path.strip_prefix(&live_prefix) {
            // Live: the Xtream path segment carries no `/live/` marker and no extension — the live
            // route accepts either, so none is added.
            uri_path = format!("/live/{proxy_user}/{proxy_pass}/{stream_id}");
        } else {
            uri_path = uri_path
                .replace(&xtream_user, &proxy_user)
                .replace(&xtream_pass, &proxy_pass);
        }
    } else {
        uri_path = join_path(
            anti_collision,
            &proxy_user,
            &proxy_pass,
            &track_index.to_string(),
            parsed.base(),
        );
    }

    let basic_auth = match &parsed.userinfo {
        Some(info) => format!("{info}@"),
        None => String::new(),
    };

    Ok(format!(
        "{}://{}{}:{}{}{}",
        config.protocol(),
        basic_auth,
        config.host_config.hostname,
        config.advertised_port,
        custom_end,
        uri_path
    ))
}

/// `path.Join("/", parts..)` — skips empty components and collapses duplicate slashes.
fn join_path(parts: &str, rest: &str, more: &str, index: &str, base: &str) -> String {
    let mut out = String::from("/");
    for part in [parts, rest, more, index, base] {
        let part = part.trim_matches('/');
        if part.is_empty() {
            continue;
        }
        if !out.ends_with('/') {
            out.push('/');
        }
        out.push_str(part);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::CredentialString;
    use crate::config::HostConfiguration;
    use std::path::PathBuf;

    fn config() -> ProxyConfig {
        ProxyConfig {
            host_config: HostConfiguration {
                hostname: "proxy.example".to_string(),
                port: 8080,
            },
            remote_url: String::new(),
            xtream_user: CredentialString::new("xuser"),
            xtream_password: CredentialString::new("xpass"),
            xtream_base_url: "http://provider:80".to_string(),
            xtream_generate_api_get: false,
            m3u_cache_expiration: 1,
            m3u_file_name: "iptv.m3u".to_string(),
            custom_endpoint: String::new(),
            custom_id: "abcd1234".to_string(),
            advertised_port: 8080,
            https: false,
            user: CredentialString::new("puser"),
            password: CredentialString::new("ppass"),
            rate_limit_retry_timeout: 10,
            category_filters_path: PathBuf::from("/tmp/filters.json"),
            redis_url: String::new(),
        }
    }

    #[test]
    fn plain_tracks_get_the_anticollision_path() {
        let url = rewrite_uri(
            &config(),
            "abcd1234",
            "http://cdn.example.com:9999/video/abc.ts?token=secret",
            7,
            false,
        )
        .unwrap();
        assert_eq!(
            url,
            "http://proxy.example:8080/abcd1234/puser/ppass/7/abc.ts"
        );
    }

    #[test]
    fn live_xtream_entries_gain_the_live_prefix() {
        let url = rewrite_uri(
            &config(),
            "anti",
            "http://provider:80/xuser/xpass/1608071",
            0,
            true,
        )
        .unwrap();
        assert_eq!(url, "http://proxy.example:8080/live/puser/ppass/1608071");
    }

    #[test]
    fn movie_and_series_entries_keep_their_prefix() {
        let movie = rewrite_uri(
            &config(),
            "anti",
            "http://provider:80/movie/xuser/xpass/999.mkv",
            0,
            true,
        )
        .unwrap();
        assert_eq!(movie, "http://proxy.example:8080/movie/puser/ppass/999.mkv");

        let series = rewrite_uri(
            &config(),
            "anti",
            "http://provider:80/series/xuser/xpass/1594663.mp4",
            0,
            true,
        )
        .unwrap();
        assert_eq!(
            series,
            "http://proxy.example:8080/series/puser/ppass/1594663.mp4"
        );
    }

    #[test]
    fn https_custom_endpoint_and_basic_auth_are_honoured() {
        let mut cfg = config();
        cfg.https = true;
        cfg.custom_endpoint = "/tv".to_string();
        cfg.advertised_port = 8443;
        let url = rewrite_uri(&cfg, "anti", "https://u2:p2@cdn.example/a/b.mp4", 3, false).unwrap();
        assert_eq!(
            url,
            "https://u2:p2@proxy.example:8443/tv/anti/puser/ppass/3/b.mp4"
        );
    }

    #[test]
    fn credentials_with_reserved_characters_are_escaped_once() {
        let mut cfg = config();
        cfg.user = CredentialString::new("a/b");
        cfg.password = CredentialString::new("p ss");
        let url = rewrite_uri(&cfg, "anti", "http://cdn/x/y.ts", 1, false).unwrap();
        assert_eq!(url, "http://proxy.example:8080/anti/a%2Fb/p%20ss/1/y.ts");
    }

    #[test]
    fn an_empty_anticollision_token_collapses_like_go_path_join() {
        let url = rewrite_uri(&config(), "", "http://cdn/x/y.ts", 2, false).unwrap();
        assert_eq!(url, "http://proxy.example:8080/puser/ppass/2/y.ts");
    }

    #[test]
    fn unparseable_uris_are_errors() {
        assert!(rewrite_uri(&config(), "anti", "no scheme", 0, false).is_err());
    }
}
